export const GREGORIAN_ADOPTION_START = 1582;
export const GREGORIAN_ADOPTION_END = 1927;

/** Sorted years in which at least one country adopted the Gregorian calendar. */
export const GREGORIAN_ADOPTION_EVENT_YEARS = [
  ...new Set(Object.values(GREGORIAN_ADOPTION_YEARS)),
].sort((a, b) => a - b);

export function getAdoptedCountryIds(asOfYear: number): string[] {
  return Object.entries(GREGORIAN_ADOPTION_YEARS)
    .filter(([, year]) => year <= asOfYear)
    .map(([id]) => id);
}

export function getCountriesAdoptedInYear(year: number): string[] {
  return Object.entries(GREGORIAN_ADOPTION_YEARS)
    .filter(([, adoptionYear]) => adoptionYear === year)
    .map(([id]) => id);
}
